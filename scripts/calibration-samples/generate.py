def video_sample(tmp):
    rng = random.Random(707)
    digits = rng.sample(range(10), 6)
    seg = 1.5
    fps = 10
    w, h = 480, 270
    total = seg * len(digits)
    raw = os.path.join(tmp, "now.wav")
    say("now", raw)
    word = read_wav(raw)
    peak = max(abs(v) for v in word)
    voiced = [i for i, v in enumerate(word) if abs(v) > peak * 0.05]
    v0, v1 = voiced[0], voiced[-1]
    target = rng.randrange(1, len(digits) - 1)
    centre = (target + 0.5) * seg
    onset = centre - (v1 - v0) / 2 / RATE
    track = [rng.gauss(0, 1) * 30 for _ in range(int(total * RATE))]
    base = int(onset * RATE) - v0
    for i, v in enumerate(word):
        track[base + i] += v
    wav = os.path.join(tmp, "track.wav")
    write_wav(wav, track)
    said_from, said_to = onset, onset + (v1 - v0) / RATE
    assert int(said_from // seg) == int(said_to // seg) == target
    answer = digits[target]

    fnt = font("sans", "Bold", 190)
    colors = [(24, 52, 92), (86, 34, 70), (28, 76, 62), (92, 58, 24), (60, 34, 96), (30, 62, 86)]
    frames = []
    for k, dg in enumerate(digits):
        im = Image.new("RGB", (w, h), colors[k % len(colors)])
        dd = ImageDraw.Draw(im)
        bb = dd.textbbox((0, 0), str(dg), font=fnt)
        dd.text(((w - (bb[2] - bb[0])) / 2 - bb[0], (h - (bb[3] - bb[1])) / 2 - bb[1]), str(dg), font=fnt,
                fill=(240, 240, 240))
        frames.append(im.tobytes())
    stdin = b"".join(frames[int(i / fps // seg)] for i in range(int(total * fps)))
    dst = os.path.join(OUT, "digits.mp4")
    subprocess.run(["ffmpeg", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{w}x{h}", "-r", str(fps),
                    "-i", "-", "-i", wav, "-c:v", "libx264", "-preset", "veryslow", "-crf", "30",
                    "-pix_fmt", "yuv420p", "-x264-params", "threads=1", "-c:a", "aac", "-b:a", "32k",
                    "-ar", str(RATE), "-ac", "1", "-shortest", "-fflags", "+bitexact", "-flags:v", "+bitexact",
                    "-flags:a", "+bitexact", "-movflags", "+faststart", "-map_metadata", "-1", dst],
                   input=stdin, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    add(id="video-digit", use_case="video-understand", file="digits.mp4",
        prompt="In this video a large digit changes every second and a half. A voice says one word during the "
               "clip. Which digit is on screen while the voice speaks?",
        answer=str(answer), check="number", tolerance=0,
        source=f"{GEN}; large digits changing every {seg} s with synthetic speech of one word "
               f"({said_from:.2f}-{said_to:.2f} s) during digit {target + 1} of {len(digits)}",
        license="CC0-1.0")


# 8: math --------------------------------------------------------------------------------------

def math_samples():
    first, step, goal = 18, 4, 200
    made, size = 0, first
    while True:
        made += size
        if made >= goal:
            break
        size += step
    add(id="math-1", use_case="math-reasoning",
        prompt=f"A bakery bakes in batches. The first batch makes {first} loaves, and every later batch makes "
               f"{step} more loaves than the batch before it. The bakery keeps baking batch after batch until "
               f"its running total reaches {goal} loaves or more. How many loaves are in the final batch?",
        answer=str(size), check="number", tolerance=0,
        source=f"{GEN}; word problem written for this set, answer computed by simulation", license="CC0-1.0")

    hi, a, b, c = 600, 6, 10, 4
    count = sum(1 for n in range(1, hi + 1) if (n % a == 0 or n % b == 0) and n % c != 0)
    add(id="math-2", use_case="math-reasoning",
        prompt=f"How many whole numbers from 1 to {hi}, inclusive, are divisible by {a} or by {b} "
               f"but are not divisible by {c}?",
        answer=str(count), check="number", tolerance=0,
        source=f"{GEN}; counting problem written for this set, answer computed by enumeration",
        license="CC0-1.0")


