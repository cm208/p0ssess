def pdf_sample(tmp):
    rng = random.Random(606)
    products = ["Alder Lamp", "Birch Shelf", "Cedar Stool", "Dune Rug", "Elm Cabinet"]
    table = {p: [rng.randint(210, 1890) for _ in range(4)] for p in products}
    asked = products[rng.randrange(len(products))]
    q = 3
    answer = table[asked][q - 1]

    cols = [72, 230, 310, 390, 470, 540]
    rowh = 26
    top = 700
    cs = []

    def text(x, y, s, bold=False, size=11):
        cs.append(f"BT /{'F2' if bold else 'F1'} {size} Tf {x} {y} Td ({s}) Tj ET")

    text(72, 750, "Quarterly units sold by product, 2026", True, 15)
    text(72, 728, "Figures are units shipped per quarter.", False, 10)
    nrows = len(products) + 1
    for i in range(nrows + 1):
        yy = top - i * rowh
        cs.append(f"0.5 w {cols[0]} {yy} m {cols[-1]} {yy} l S")
    for x in cols:
        cs.append(f"0.5 w {x} {top} m {x} {top - nrows * rowh} l S")
    for j, hdr in enumerate(["Product", "Q1", "Q2", "Q3", "Q4"]):
        text(cols[j] + 6, top - 18, hdr, True)
    for i, p in enumerate(products):
        yy = top - (i + 2) * rowh + 8
        text(cols[0] + 6, yy, p)
        for j, v in enumerate(table[p]):
            text(cols[j + 1] + 6, yy, str(v))
    stream = "\n".join(cs).encode("latin-1")
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offs = []
    for i, o in enumerate(objs, 1):
        offs.append(len(out))
        out += b"%d 0 obj\n" % i + o + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    for o in offs:
        out += b"%010d 00000 n \n" % o
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)
    with open(os.path.join(OUT, "table.pdf"), "wb") as f:
        f.write(out)
    add(id="pdf-table", use_case="pdf-table-extract", file="table.pdf",
        prompt=f"In the table in this PDF, what is the Q{q} figure for {asked}?",
        answer=str(answer), check="number", tolerance=0,
        source=f"{GEN}; one-page text PDF with a table of made-up quarterly figures", license="CC0-1.0")


