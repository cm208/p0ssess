# 10: code -------------------------------------------------------------------------------------

CODE = '''def bucket(n):
    if n % 3 == 0:
        return 1
    if n % 5 == 0:
        return 2
    return 0 if n % 2 else 3


def weigh(values, limit):
    total = 0
    streak = 0
    for v in values:
        b = bucket(v)
        if b == 0:
            streak = 0
            continue
        streak += 1
        total += b * streak
        if total > limit:
            break
    return total, streak


def gather(start, count, step):
    out = []
    n = start
    while len(out) < count:
        if n % 4 != 1:
            out.append(n)
        n += step
    return out


def report():
    data = gather(7, 12, 5)
    total, streak = weigh(data, 30)
    return total * 10 + streak
'''


def code_sample(tmp):
    with open(os.path.join(OUT, "weigh.py"), "w") as f:
        f.write(CODE)
    ns = {}
    exec(compile(CODE, "weigh.py", "exec"), ns)
    answer = ns["report"]()
    add(id="code-return", use_case="code-analysis", file="weigh.py",
        prompt="What integer does the function report() return when called with no arguments in this Python file?",
        answer=str(answer), check="number", tolerance=0,
        source=f"{GEN}; small Python module written for this set, answer computed by running it",
        license="CC0-1.0")


# manifest -------------------------------------------------------------------------------------

def q(s):
    return json.dumps(s, ensure_ascii=True)


def write_manifest():
    order = ["transcribe-clean", "transcribe-radio", "beeps", "ocr-label", "receipt-total", "pdf-table",
             "video-digit", "math-1", "math-2", "records-count", "code-return"]
    by_id = {s["id"]: s for s in samples}
    keys = ["id", "use_case", "file", "prompt", "output", "answer", "check", "tolerance", "max_wer",
            "source", "license"]
    out = [HEADER]
    for i in order:
        s = by_id[i]
        out.append("\n[[sample]]\n")
        for k in keys:
            if k not in s:
                continue
            v = s[k]
            out.append(f"{k} = {q(v) if isinstance(v, str) else v}\n")
    with open(os.path.join(OUT, "answers.toml"), "w") as f:
        f.write("".join(out))


def main():
    os.makedirs(OUT, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        speech_samples(tmp)
        beeps_sample(tmp)
        ocr_sample(tmp)
        receipt_sample(tmp)
        pdf_sample(tmp)
        video_sample(tmp)
        math_samples()
        records_sample(tmp)
        code_sample(tmp)
    write_manifest()
    for s in samples:
        print(f"{s['id']:18} {s['answer'][:40]}")


if __name__ == "__main__":
    main()
