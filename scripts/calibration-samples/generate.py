#!/usr/bin/env python3
"""Regenerate the built-in calibration samples and their answer key.

Needs Python 3 with Pillow, ffmpeg, flite and the Liberation fonts. Every answer in answers.toml is
computed here from the same data that produced the sample file.
"""
import array
import csv
import glob
import json
import math
import os
import random
import subprocess
import sys
import tempfile
import wave

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "internal", "calibrate", "samples"))
GEN = "generated by scripts/calibration-samples/generate.py"
RATE = 16000

HEADER = """# Built-in calibration samples. Every file here is generated by p0ssess's own script
# (scripts/calibration-samples) or is public domain or CC0; each sample names its source and license.
"""

samples = []


def add(**kw):
    samples.append(kw)


def run(*cmd, **kw):
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **kw)


def font(family, style, size):
    hits = glob.glob(f"/usr/share/fonts/liberation-{family}*/Liberation{family.title()}-{style}.ttf")
    if not hits:
        sys.exit(f"Liberation {family} {style} not found")
    return ImageFont.truetype(hits[0], size)


def say(text, path):
    run("flite", "-voice", "slt", "-t", text, path)


def read_wav(path):
    with wave.open(path) as w:
        assert w.getframerate() == RATE and w.getnchannels() == 1 and w.getsampwidth() == 2
        a = array.array("h")
        a.frombytes(w.readframes(w.getnframes()))
    return a


def write_wav(path, samp):
    a = array.array("h", [max(-32768, min(32767, int(round(v)))) for v in samp])
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(a.tobytes())


def rms(a):
    return math.sqrt(sum(v * v for v in a) / len(a))


def mp3(src, dst):
    run("ffmpeg", "-y", "-i", src, "-ac", "1", "-ar", str(RATE), "-c:a", "libmp3lame", "-b:a", "32k",
        "-fflags", "+bitexact", "-flags:a", "+bitexact", "-write_xing", "0", dst)


# 1 and 2: speech ------------------------------------------------------------------------------

CLEAN_TEXT = ("The Mole had been working very hard all the morning, spring cleaning his little home. "
              "First with brooms, then with dusters; then on ladders and steps and chairs, "
              "with a brush and a pail of whitewash.")
RADIO_TEXT = ("Alice was beginning to get very tired of sitting by her sister on the bank, and of having "
              "nothing to do. Once or twice she had peeped into the book her sister was reading, "
              "but it had no pictures or conversations in it.")


def speech_samples(tmp):
    raw = os.path.join(tmp, "clean.wav")
    say(CLEAN_TEXT, raw)
    mp3(raw, os.path.join(OUT, "clean.mp3"))
    add(id="transcribe-clean", use_case="audio-transcribe", file="clean.mp3", output="transcript",
        prompt="Transcribe the speech.", answer=CLEAN_TEXT, check="wer", max_wer=0.25,
        source=f"{GEN}; synthetic speech reading an excerpt of Grahame, The Wind in the Willows (1908), public domain",
        license="CC0-1.0")

    raw = os.path.join(tmp, "radio.wav")
    say(RADIO_TEXT, raw)
    speech = read_wav(raw)
    lead = [0] * (RATE // 2)
    padded = os.path.join(tmp, "radio_pad.wav")
    write_wav(padded, lead + list(speech) + lead)
    noise = os.path.join(tmp, "noise.wav")
    dur = (len(speech) + RATE) / RATE
    run("ffmpeg", "-y", "-f", "lavfi", "-i",
        f"anoisesrc=color=pink:sample_rate={RATE}:amplitude=0.5:seed=7:duration={dur:.3f}",
        "-ac", "1", "-sample_fmt", "s16", noise)
    band = "highpass=f=300,lowpass=f=3000"
    sp_b, nz_b = os.path.join(tmp, "sp_b.wav"), os.path.join(tmp, "nz_b.wav")
    run("ffmpeg", "-y", "-i", padded, "-af", band, "-sample_fmt", "s16", sp_b)
    run("ffmpeg", "-y", "-i", noise, "-af", band, "-sample_fmt", "s16", nz_b)
    sp, nz = read_wav(sp_b), read_wav(nz_b)
    n = min(len(sp), len(nz))
    snr_db = SNR_DB
    gain = rms([v for v in sp[:n] if abs(v) > 0]) / rms(nz[:n]) / (10 ** (snr_db / 20))
    mix = [sp[i] + nz[i] * gain for i in range(n)]
    peak = max(abs(v) for v in mix)
    mix = [v * 26000 / peak for v in mix]
    mixed = os.path.join(tmp, "radio_mix.wav")
    write_wav(mixed, mix)
    mp3(mixed, os.path.join(OUT, "radio.mp3"))
    add(id="transcribe-radio", use_case="audio-transcribe-noisy", file="radio.mp3", output="transcript",
        prompt="Transcribe the speech.", answer=RADIO_TEXT, check="wer", max_wer=0.4,
        source=f"{GEN}; synthetic speech over band-limited pink noise, reading an excerpt of "
               "Carroll, Alice's Adventures in Wonderland (1865), public domain",
        license="CC0-1.0")


SNR_DB = 6.0


# 3: beeps -------------------------------------------------------------------------------------

def beeps_sample(tmp):
    rng = random.Random(303)
    dur = 10.0
    n = 6
    slots = [0.5 + i * 1.5 for i in range(n)]
    starts = [s + rng.uniform(0.0, 0.7) for s in slots]
    sig = [rng.gauss(0, 1) * 250 for _ in range(int(dur * RATE))]
    prev = 0.0
    for i, v in enumerate(sig):
        prev = 0.6 * prev + 0.4 * v
        sig[i] = prev
    for st in starts:
        length = rng.uniform(0.18, 0.4)
        f = rng.choice([660, 880, 1100, 1320])
        a0 = int(st * RATE)
        m = int(length * RATE)
        for k in range(m):
            env = min(1.0, k / 160, (m - k) / 160)
            sig[a0 + k] += 9000 * env * math.sin(2 * math.pi * f * k / RATE)
    raw = os.path.join(tmp, "beeps.wav")
    write_wav(raw, sig)
    mp3(raw, os.path.join(OUT, "beeps.mp3"))
    add(id="beeps", use_case="audio-events", file="beeps.mp3",
        prompt="This clip contains short beeps (pure tones) over faint background hiss. How many separate "
               "beeps are there?",
        answer=str(n), check="number", tolerance=0,
        source=f"{GEN}; sine-tone beeps at irregular times over low-level noise", license="CC0-1.0")


