def ocr_sample(tmp):
    rng = random.Random(404)
    letters = "QXKMRTWZ"
    code = "{}{}-{}-{}".format(rng.choice(letters), rng.choice(letters),
                               "".join(rng.choice("2345679") for _ in range(5)), rng.choice("KMRTWZ"))
    w, h = 900, 360
    bg = (222, 222, 214)
    img = Image.new("RGB", (w, h), bg)
    d = ImageDraw.Draw(img)
    d.rectangle([20, 20, w - 21, h - 21], outline=(70, 70, 70), width=4)
    d.text((50, 45), "PART CODE", font=font("sans", "Bold", 34), fill=(60, 60, 60))
    d.text((50, 110), code, font=font("mono", "Bold", 118), fill=(35, 35, 35))
    d.text((50, 270), "REV C    QTY 24    BIN 07", font=font("sans", "Regular", 30), fill=(80, 80, 80))
    x = 640
    for _ in range(34):
        bw = rng.choice([2, 3, 5])
        d.rectangle([x, 285, x + bw - 1, 325], fill=(50, 50, 50))
        x += bw + rng.choice([2, 3, 4])
    img = img.rotate(3.4, resample=Image.BICUBIC, expand=True, fillcolor=bg)
    img = img.filter(ImageFilter.GaussianBlur(2.6))
    px = img.load()
    nrng = random.Random(405)
    for yy in range(img.height):
        for xx in range(img.width):
            r, g, b = px[xx, yy]
            nv = nrng.gauss(0, 15) + 22 * xx / img.width
            r, g, b = (int(60 + (c - 20) * 0.5 + nv) for c in (r, g, b))
            px[xx, yy] = (max(0, min(255, r)), max(0, min(255, g)), max(0, min(255, b)))
    img = img.resize((img.width * 2 // 3, img.height * 2 // 3), Image.BILINEAR)
    img.save(os.path.join(OUT, "label.jpg"), quality=22, optimize=True, subsampling=2)
    add(id="ocr-label", use_case="ocr-degraded-image", file="label.jpg",
        prompt="This is a degraded image of a parts label. What is the part code printed in large type?",
        answer=code, check="exact",
        source=f"{GEN}; rendered label with a made-up code, then rotated, blurred, noised and JPEG-compressed",
        license="CC0-1.0")


