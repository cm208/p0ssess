def receipt_sample(tmp):
    rng = random.Random(505)
    pool = ["OAT MILK 1L", "RYE BREAD", "BASIL PLANT", "FREE RANGE EGGS", "DARK CHOCOLATE", "LEMONS 4CT",
            "SPARKLING WATER", "COFFEE BEANS 340G", "BUTTER", "TOMATO PASTE"]
    items = [(name, rng.randint(179, 1299)) for name in rng.sample(pool, 5)]
    total = sum(c for _, c in items)
    cash = (total // 1000 + 1) * 1000
    fm = font("mono", "Regular", 22)
    fb = font("mono", "Bold", 26)
    w, line = 480, 34
    rows = ["MARROWBY & FERN GROCERS", "214 Quillon Street", "", "THU 12 NOV 2026  14:07", "REG 03   ORDER 88213", ""]
    rows += [f"{n:<24}{c / 100:>8.2f}" for n, c in items]
    rows += ["-" * 32]
    h = 60 + line * (len(rows) + 6)
    img = Image.new("L", (w, h), 246)
    d = ImageDraw.Draw(img)
    y = 30
    for i, r in enumerate(rows):
        f = fb if i == 0 else fm
        if i < 2:
            f = font("mono", "Bold", 22) if i == 1 else f
            tw = d.textlength(r, font=f)
            d.text(((w - tw) / 2, y), r, font=f, fill=30)
